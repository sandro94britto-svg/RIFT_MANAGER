import { MATCH_STATUS }
from "./matchStatuses";

// =====================================================

let matchAutoId = 1;

// =====================================================

export function createMatch({
  competitionId,
  stageType,
  round,
  scheduledDate,

  homeTeamId,
  awayTeamId,

  bestOf = 1,
  fearlessDraft = false,
}) {

  return {

    // -------------------------------------------------
    // IDs
    // -------------------------------------------------

    id: `match_${matchAutoId++}`,

    // -------------------------------------------------
    // COMPETITION
    // -------------------------------------------------

    competitionId,
    stageType,
    round,

    // -------------------------------------------------
    // TEAMS
    // -------------------------------------------------

    homeTeamId,
    awayTeamId,

    // -------------------------------------------------
    // FORMAT
    // -------------------------------------------------

    bestOf,
    fearlessDraft,

    // -------------------------------------------------
    // DATE
    // -------------------------------------------------

    scheduledDate,

    // -------------------------------------------------
    // STATE
    // -------------------------------------------------

    status: MATCH_STATUS.SCHEDULED,

    // -------------------------------------------------
    // RESULT
    // -------------------------------------------------

    winnerTeamId: null,
    loserTeamId: null,

    homeScore: 0,
    awayScore: 0,

    games: [],

  };
}